"""Policy engine: decides whether a tool call is auto-approved, needs approval, or is blocked."""

from __future__ import annotations

import enum
import tomllib
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

from mi_core.config import mi_home
from mi_core.tools.registry import Tier, ToolDef


class Decision(enum.Enum):
    AUTO = "auto"
    ASK = "ask"
    REFUSE = "refuse"


class PolicyRule(BaseModel):
    tool: str = "*"
    args_match: dict[str, str] = Field(default_factory=dict)
    decision: Decision = Decision.AUTO


class PolicyResult(BaseModel):
    decision: Decision
    effective_tier: Tier
    reason: str = ""


def policy_path() -> Path:
    return mi_home() / "policy.toml"


def _load_rules() -> list[PolicyRule]:
    path = policy_path()
    if not path.exists():
        return []
    with path.open("rb") as f:
        raw = tomllib.load(f)
    rules = []
    for entry in raw.get("allow", []):
        rules.append(PolicyRule(tool=entry.get("tool", "*"), decision=Decision.AUTO))
    return rules


def _matches_allowlist(tool_name: str, args: dict[str, Any], rules: list[PolicyRule]) -> bool:
    for rule in rules:
        if rule.decision != Decision.AUTO:
            continue
        if rule.tool == "*" or rule.tool == tool_name:
            if not rule.args_match:
                return True
            if all(str(args.get(k)) == v for k, v in rule.args_match.items()):
                return True
    return False


def check_policy(
    tool_def: ToolDef,
    args: dict[str, Any],
    tainted: bool = False,
    autonomy: str = "normal",
    scheduled: bool = False,
) -> PolicyResult:
    tier = tool_def.tier

    if tier == Tier.BLOCKED:
        return PolicyResult(
            decision=Decision.REFUSE,
            effective_tier=Tier.BLOCKED,
            reason=f"{tool_def.name} is BLOCKED and cannot be executed.",
        )

    if tainted and tier < Tier.CONFIRM:
        tier = tier.escalated()

    if autonomy == "dry_run":
        return PolicyResult(
            decision=Decision.ASK,
            effective_tier=tier,
            reason="Dry-run mode: all actions require approval.",
        )

    if autonomy == "paused":
        return PolicyResult(
            decision=Decision.REFUSE,
            effective_tier=tier,
            reason="Autonomy is paused.",
        )

    if scheduled and tier >= Tier.CONFIRM:
        return PolicyResult(
            decision=Decision.ASK,
            effective_tier=tier,
            reason="Scheduled runs never auto-approve CONFIRM tools.",
        )

    if tier == Tier.CONFIRM:
        rules = _load_rules()
        if _matches_allowlist(tool_def.name, args, rules):
            return PolicyResult(
                decision=Decision.AUTO,
                effective_tier=tier,
                reason="Allowed by policy.toml rule.",
            )
        return PolicyResult(
            decision=Decision.ASK,
            effective_tier=tier,
            reason=f"{tool_def.name} requires approval (tier CONFIRM).",
        )

    return PolicyResult(decision=Decision.AUTO, effective_tier=tier)


def add_allow_rule(tool_name: str, args_pattern: dict[str, str] | None = None) -> None:
    path = policy_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = ""
    if path.exists():
        existing = path.read_text(encoding="utf-8")
    if not existing.strip():
        existing = "# mi policy rules (auto-generated by approve_always)\n"
    entry = f'\n[[allow]]\ntool = "{tool_name}"\n'
    if args_pattern:
        for k, v in args_pattern.items():
            entry += f'{k} = "{v}"\n'
    path.write_text(existing + entry, encoding="utf-8")
